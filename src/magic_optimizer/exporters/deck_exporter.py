import json
import os
from datetime import datetime
from typing import Dict, List


class DeckExporter:
    """Centralized deck exporter for multiple formats"""

    def __init__(self, run_folder: str = "runs"):
        self.run_folder = run_folder
        self.timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        self.run_path = os.path.join(run_folder, self.timestamp)

        # Create run directory
        os.makedirs(self.run_path, exist_ok=True)

    def export_deck(
        self,
        deck: List[Dict],
        algorithm: str,
        target_colors: List[str],
        score: float,
        formats: List[str] = None,
    ) -> Dict:
        """
        Export deck in multiple formats

        Args:
            deck: List of card dictionaries
            algorithm: Algorithm used for optimization
            target_colors: Target colors for the deck
            score: Final deck score
            formats: List of export formats
        """
        if formats is None:
            formats = ["copy_paste", "arena"]

        exported_files = {}

        for format_type in formats:
            try:
                filename = self._export_format(
                    deck, algorithm, target_colors, score, format_type
                )
                exported_files[format_type] = filename
                print(f"Exported to {filename}")
            except Exception as e:
                print(f"Error exporting {format_type} format: {e}")
                exported_files[format_type] = None

        return exported_files

    def _export_format(
        self,
        deck: List[Dict],
        algorithm: str,
        target_colors: List[str],
        score: float,
        format_type: str,
    ) -> str:
        """Export deck in specific format"""

        if format_type == "arena":
            return self._export_arena_format(deck, algorithm, target_colors, score)
        elif format_type == "mtgo":
            return self._export_mtgo_format(deck, algorithm, target_colors, score)
        elif format_type == "cockatrice":
            return self._export_cockatrice_format(deck, algorithm, target_colors, score)
        elif format_type == "tappedout":
            return self._export_tappedout_format(deck, algorithm, target_colors, score)
        elif format_type == "archidekt":
            return self._export_archidekt_format(deck, algorithm, target_colors, score)
        elif format_type == "moxfield":
            return self._export_moxfield_format(deck, algorithm, target_colors, score)
        elif format_type == "copy_paste":
            return self._export_copy_paste_format(deck, algorithm, target_colors, score)
        elif format_type == "html" or format_type == "html_artwork":
            return self._export_html_artwork_format(
                deck, algorithm, target_colors, score
            )
        else:
            raise ValueError(f"Unknown format: {format_type}")

    def _export_arena_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in MTG Arena format"""
        filename = os.path.join(self.run_path, f"deck_arena_{algorithm}.txt")
        with open(filename, "w") as f:
            f.write(f"# Generated by Magic Optimizer\n")
            f.write(f"# Algorithm: {algorithm}\n")
            f.write(f"# Colors: {', '.join(target_colors)}\n")
            f.write(f"# Score: {score:.4f}\n")
            f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            for card in deck:
                f.write(f"1 {card['name']}\n")
        return filename

    def _export_mtgo_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in MTGO format"""
        filename = os.path.join(self.run_path, f"deck_mtgo_{algorithm}.txt")
        with open(filename, "w") as f:
            f.write(f"# Generated by Magic Optimizer\n")
            f.write(f"# Algorithm: {algorithm}\n")
            f.write(f"# Colors: {', '.join(target_colors)}\n")
            f.write(f"# Score: {score:.4f}\n")
            f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            for card in deck:
                f.write(f"1 {card['name']}\n")
        return filename

    def _export_cockatrice_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in Cockatrice XML format"""
        filename = os.path.join(self.run_path, f"deck_cockatrice_{algorithm}.cod")
        with open(filename, "w") as f:
            f.write('<?xml version="1.0" encoding="UTF-8"?>\n')
            f.write('<cockatrice_deck version="1">\n')
            f.write(f"  <deckname>Optimal Deck ({algorithm})</deckname>\n")
            f.write(f"  <comments>Generated by Magic Optimizer\n")
            f.write(f"Algorithm: {algorithm}\n")
            f.write(f'Colors: {", ".join(target_colors)}\n')
            f.write(f"Score: {score:.4f}\n")
            f.write(
                f'Generated: {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}</comments>\n'
            )
            f.write('  <zone name="main">\n')
            for card in deck:
                f.write(f'    <card number="1" name="{card["name"]}"/>\n')
            f.write("  </zone>\n")
            f.write("</cockatrice_deck>\n")
        return filename

    def _export_tappedout_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in TappedOut format"""
        filename = os.path.join(self.run_path, f"deck_tappedout_{algorithm}.txt")
        with open(filename, "w") as f:
            f.write(f"# Generated by Magic Optimizer\n")
            f.write(f"# Algorithm: {algorithm}\n")
            f.write(f"# Colors: {', '.join(target_colors)}\n")
            f.write(f"# Score: {score:.4f}\n")
            f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            for card in deck:
                f.write(f"1 {card['name']}\n")
        return filename

    def _export_archidekt_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in Archidekt JSON format"""
        filename = os.path.join(self.run_path, f"deck_archidekt_{algorithm}.json")
        deck_data = {
            "name": f"Optimal Deck ({algorithm})",
            "description": f"Generated by Magic Optimizer\nAlgorithm: {algorithm}\nColors: {', '.join(target_colors)}\nScore: {score:.4f}",
            "cards": [],
        }

        for card in deck:
            deck_data["cards"].append({"name": card["name"], "quantity": 1})

        with open(filename, "w") as f:
            json.dump(deck_data, f, indent=2)
        return filename

    def _export_moxfield_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in Moxfield format"""
        filename = os.path.join(self.run_path, f"deck_moxfield_{algorithm}.txt")
        with open(filename, "w") as f:
            f.write(f"# Generated by Magic Optimizer\n")
            f.write(f"# Algorithm: {algorithm}\n")
            f.write(f"# Colors: {', '.join(target_colors)}\n")
            f.write(f"# Score: {score:.4f}\n")
            f.write(f"# Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            for card in deck:
                f.write(f"1 {card['name']}\n")
        return filename

    def _export_copy_paste_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck in simple copy-paste format"""
        filename = os.path.join(self.run_path, f"deck_copy_paste_{algorithm}.txt")
        with open(filename, "w") as f:
            f.write("=== OPTIMAL DECK ===\n")
            f.write(f"Generated by Magic Optimizer\n")
            f.write(f"Algorithm: {algorithm}\n")
            f.write(f"Colors: {', '.join(target_colors)}\n")
            f.write(f"Score: {score:.4f}\n")
            f.write(f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")
            for i, card in enumerate(deck, 1):
                colors_str = (
                    ", ".join(card["colors"]) if card["colors"] else "Colorless"
                )
                f.write(
                    f"{i:2d}. {card['rating']}/10 - {card['name']} ({colors_str}, {card['cmc']} CMC)\n"
                )
        return filename

    def _export_html_artwork_format(
        self, deck: List[Dict], algorithm: str, target_colors: List[str], score: float
    ) -> str:
        """Export deck as HTML with card artworks"""
        filename = os.path.join(self.run_path, f"deck_artwork_{algorithm}.html")

        # Get card image URLs from Scryfall
        card_images = []
        for card in deck:
            card_name = card["name"]
            # Scryfall image URL format
            image_url = f"https://api.scryfall.com/cards/named?fuzzy={card_name.replace(' ', '+')}&format=image"
            card_images.append(
                {
                    "name": card_name,
                    "image_url": image_url,
                    "rating": card.get("rating", 0),
                    "colors": card.get("colors", set()),
                    "cmc": card.get("cmc", 0),
                }
            )

        # Create HTML content
        html_content = f"""
<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Magic Optimizer Deck - {algorithm.title()}</title>
    <style>
        body {{
            font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif;
            margin: 0;
            padding: 20px;
            background: linear-gradient(135deg, #1e3c72 0%, #2a5298 100%);
            color: white;
        }}
        .header {{
            text-align: center;
            margin-bottom: 30px;
            background: rgba(0,0,0,0.3);
            padding: 20px;
            border-radius: 10px;
        }}
        .deck-info {{
            display: grid;
            grid-template-columns: repeat(auto-fit, minmax(200px, 1fr));
            gap: 20px;
            margin-bottom: 30px;
        }}
        .info-card {{
            background: rgba(255,255,255,0.1);
            padding: 15px;
            border-radius: 8px;
            text-align: center;
        }}
        .cards-grid {{
            display: grid;
            grid-template-columns: repeat(auto-fill, minmax(250px, 1fr));
            gap: 20px;
            margin-top: 30px;
        }}
        .card-container {{
            background: rgba(255,255,255,0.1);
            border-radius: 10px;
            padding: 15px;
            text-align: center;
            transition: transform 0.3s ease;
        }}
        .card-container:hover {{
            transform: translateY(-5px);
            box-shadow: 0 10px 20px rgba(0,0,0,0.3);
        }}
        .card-image {{
            width: 100%;
            max-width: 223px;
            height: auto;
            border-radius: 8px;
            margin-bottom: 10px;
            box-shadow: 0 4px 8px rgba(0,0,0,0.3);
        }}
        .card-name {{
            font-weight: bold;
            margin-bottom: 5px;
            color: #ffd700;
        }}
        .card-details {{
            font-size: 0.9em;
            color: #ccc;
        }}
        .rating {{
            color: #00ff88;
            font-weight: bold;
        }}
        .colors {{
            margin-top: 5px;
        }}
        .color-symbol {{
            display: inline-block;
            width: 20px;
            height: 20px;
            border-radius: 50%;
            margin: 0 2px;
            border: 2px solid white;
        }}
        .color-W {{ background: #f8f6d8; }}
        .color-U {{ background: #c1d7e9; }}
        .color-B {{ background: #a69f9d; }}
        .color-R {{ background: #e49977; }}
        .color-G {{ background: #a3c095; }}
        .colorless {{ background: #d4d4d4; }}
        .loading {{
            text-align: center;
            padding: 20px;
            font-style: italic;
        }}
        @media (max-width: 768px) {{
            .cards-grid {{
                grid-template-columns: repeat(auto-fill, minmax(200px, 1fr));
            }}
        }}
    </style>
</head>
<body>
    <div class="header">
        <h1>🎴 Magic Optimizer Deck</h1>
        <h2>{algorithm.title()} Algorithm</h2>
        <p>Generated on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
    </div>
    
    <div class="deck-info">
        <div class="info-card">
            <h3>🎨 Colors</h3>
            <p>{', '.join(target_colors) if target_colors else 'Colorless'}</p>
        </div>
        <div class="info-card">
            <h3>📊 Score</h3>
            <p>{score:.4f}</p>
        </div>
        <div class="info-card">
            <h3>🃏 Cards</h3>
            <p>{len(deck)}</p>
        </div>
        <div class="info-card">
            <h3>⭐ Avg Rating</h3>
            <p>{sum(card.get('rating', 0) for card in deck) / len(deck):.1f}/10</p>
        </div>
    </div>
    
    <div class="cards-grid">
"""

        # Add each card
        for i, card in enumerate(card_images, 1):
            colors_html = ""
            if card["colors"]:
                for color in card["colors"]:
                    colors_html += f'<span class="color-symbol color-{color}" title="{color}"></span>'
            else:
                colors_html = (
                    '<span class="color-symbol colorless" title="Colorless"></span>'
                )

            html_content += f"""
        <div class="card-container">
            <img src="{card['image_url']}" alt="{card['name']}" class="card-image" 
                 onerror="this.style.display='none'; this.nextElementSibling.style.display='block';">
            <div class="loading" style="display:none;">Image not available</div>
            <div class="card-name">{card['name']}</div>
            <div class="card-details">
                <div class="rating">Rating: {card['rating']}/10</div>
                <div>CMC: {card['cmc']}</div>
                <div class="colors">{colors_html}</div>
            </div>
        </div>
"""

        html_content += """
    </div>
    
    <script>
        // Add loading states and error handling
        document.addEventListener('DOMContentLoaded', function() {
            const images = document.querySelectorAll('.card-image');
            images.forEach(img => {
                img.addEventListener('load', function() {
                    this.style.opacity = '1';
                });
                img.addEventListener('error', function() {
                    this.style.display = 'none';
                    this.nextElementSibling.style.display = 'block';
                });
            });
        });
    </script>
</body>
</html>
"""

        with open(filename, "w", encoding="utf-8") as f:
            f.write(html_content)

        return filename
